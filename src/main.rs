const AKSANLI: &[(char, char, Aksan)] = &[
    ('Ç', 'C', Aksan::Cengel),
    ('Ş', 'S', Aksan::Cengel),
    ('Ğ', 'G', Aksan::Kisa),
    ('İ', 'I', Aksan::Nokta),
    ('Ö', 'O', Aksan::IkiNokta),
    ('Ü', 'U', Aksan::IkiNokta)
];

const HUCRE: usize = 12;

fn govde(harf: char) -> Option<[&'static str; 7]> {
    HARFLER.iter().find(|(h, _)| *h == harf).map(|(_, g)| *g)
}

fn glif(harf: char) -> Vec<String> {
    if harf == ' ' {
        return vec!["...".to_string(); HUCRE];
    }
    let aksan = AKSANLI.iter().find(|(h, _, _)| *h == harf);
    let temel = aksan.map(|(_, t, _)| *t).unwrap_or(harf);
    let g = govde(temel).or_else(|| govde('-')).unwrap();
    let genislik = g[0].len();
    let mut satirlar = vec![".".repeat(genislik); HUCRE];
    for (i, s) in g.iter().enumerate() {
        satirlar[3 + i] = s.to_string();
    }
    if let Some((_, _, a)) = aksan {
        let ekler: &[(usize, &str)] = match a {
            Aksan::Nokta => &[(1, ".#.")],
            Aksan::IkiNokta => &[(1, ".#.#.")],
            Aksan::Kisa => &[(0, "#...#"), (1, ".###.")],
            Aksan::Cengel => &[(10, "..#.."), (11, ".##..")],
        };
        for (i, s) in ekler {
            let mut satir: String = s.chars().take(genislik).collect();
            while satir.len() < genislik {
                satir.push('.');
            }
            satirlar[*i] = satir;
        }
    }
    satirlar
}

fn buyut(metin: &str) -> String {
    metin
        .chars()
        .map(|c| match c {
            'i' => 'İ'.to_string(),
            'ı' => 'I'.to_string(),
            _ => c.to_uppercase().to_string(),
        })
        .collect()
}

fn main() {
    let mut renk: Option<u8> = None;
    let mut dar = false;
    let mut kelimeler: Vec<String> = Vec::new();
    let mut args = env::args().skip(1);
    while let Some(a) = args.next() {
        if a == "-h" || a == "--yardim" {
            println!("Kullanım: piksel-terminal [--renk 0-255] [--dar] METİN");
            println!("Metni 5x7 piksel yazı tipiyle terminale basar. Türkçe harfler desteklenir.");
            println!("Örnek: piksel-terminal --renk 141 DEOKWAVE");
            return;
        }
        if a == "--dar" {
            dar = true;
            continue;
        }
        if a == "--renk" {
            renk = args.next().and_then(|r| r.parse().ok());
        } else {
            kelimeler.push(a);
        }
    }
    let metin = if kelimeler.is_empty() { "DEOKWAVE".to_string() } else { kelimeler.join(" ") };
    let glifler: Vec<Vec<String>> = buyut(&metin).chars().map(glif).collect();
    let (bas, son) = match renk {
        Some(r) => (format!("\x1b[38;5;{}m", r), "\x1b[0m".to_string()),
        None => (String::new(), String::new()),
    };
    for y in 0..HUCRE {
        let satir: String = glifler
            .iter()
            .map(|g| g[y].chars().map(|c| match (c == '#', dar) {
                    (true, false) => "██",
                    (false, false) => "  ",
                    (true, true) => "█",
                    (false, true) => " ",
                }).collect::<String>() + if dar { " " } else { "  " })
            .collect();
        if satir.trim().is_empty() {
            continue;
        }
        println!("{}{}{}", bas, satir.trim_end(), son);
    }
}
